def has_icon(name: str) -> bool:
    return name in ICONS


def paint_icon(
    p: QPainter,
    name: str,
    rect: QRectF,
    color: QColor,
    *,
    stroke: float = 1.7,
    scale: float = 1.0,
) -> None:
    """在 rect 内绘制 24×24 网格上的图标。"""
    shapes = ICONS.get(name)
    if not shapes:
        return
    p.save()
    p.setRenderHint(QPainter.RenderHint.Antialiasing, True)
    size = min(rect.width(), rect.height()) * scale
    ox = rect.center().x() - size / 2
    oy = rect.center().y() - size / 2
    k = size / 24.0
    # 描边宽度按实际像素给：以 24 网格设计，缩放到 size 后保持视觉粗细
    pen = QPen(color, max(1.0, stroke * (size / 24.0)))
    pen.setCapStyle(Qt.PenCapStyle.SquareCap)
    pen.setJoinStyle(Qt.PenJoinStyle.MiterJoin)
    p.setPen(pen)
    p.setBrush(Qt.BrushStyle.NoBrush)

    for kind, shape in shapes:
        if kind == "rect":
            x, y, w, h = shape
            p.drawRect(QRectF(ox + x * k, oy + y * k, w * k, h * k))
        elif kind == "circle":
            cx, cy, r = shape
            p.drawEllipse(QPointF(ox + cx * k, oy + cy * k), r * k, r * k)
        elif kind == "poly":
            from PyQt6.QtGui import QPolygonF

            poly = QPolygonF([QPointF(ox + x * k, oy + y * k) for x, y in shape])
            p.drawPolygon(poly)
        elif kind == "path":
            # 只有两个重合的点 = 圆点（图标里的网点装饰）
            if len(shape) == 2 and abs(shape[0][0] - shape[1][0]) < 0.4 and abs(shape[0][1] - shape[1][1]) < 0.4:
                px, py = shape[0]
                p.fillRect(QRectF(ox + px * k - 1.1, oy + py * k - 1.1, 2.2, 2.2), color)
                continue
            path = QPainterPath()
            first = True
            for x, y in shape:
                if first:
                    path.moveTo(ox + x * k, oy + y * k)
                    first = False
                else:
                    path.lineTo(ox + x * k, oy + y * k)
            p.drawPath(path)
    p.restore()
